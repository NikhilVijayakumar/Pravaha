def test_storage_browse_output(storage_setup):
    response = client.get("/api/storage/output/browse")
    assert response.status_code == 200
    data = response.json()
    assert isinstance(data, list)
    
    # We seeded output/TestProduct/TestFeature/result.json
    # OutputStorageProvider browse should find it and return Grouped Artifacts.
    if len(data) > 0:
        found = False
        for item in data:
            if item.get("product") == "TestProduct" and item.get("feature") == "TestFeature":
                found = True
                break
        assert found, f"Did not find TestProduct/TestFeature in {data}"

def test_storage_comprehensive_scenarios(storage_setup):
    # 1. Output (JSON content)
    # Root file
    resp = client.get("/api/storage/output/read?path=root_result.json")
    assert resp.status_code == 200
    assert resp.json()["content"]["status"] == "root"
    
    # Nested file (Valid Hierarchy)
    resp = client.get("/api/storage/output/read?path=TestProduct/TestFeature/result.json")
    assert resp.status_code == 200
    assert resp.json()["content"]["status"] == "nested"

    # 2. Intermediate (JSON content)
    # Root file
    resp = client.get("/api/storage/intermediate/read?path=step1.json")
    assert resp.status_code == 200
    assert resp.json()["content"]["step"] == 1
    
    # Nested file
    resp = client.get("/api/storage/intermediate/read?path=nested_inter/temp.json")
    assert resp.status_code == 200
    assert resp.json()["content"]["step"] == 2

    # 3. Knowledge (Markdown content)
    # Root file
    resp = client.get("/api/storage/knowledge/read?path=root_info.md")
    assert resp.status_code == 200
    assert "# Root Info" in resp.json()["content"]
    
    # Nested file
    resp = client.get("/api/storage/knowledge/read?path=nested_wiki/python.md")
    assert resp.status_code == 200
    assert "# Python" in resp.json()["content"]
    
    # 4. Verify Browsing Knowledge
    resp = client.get("/api/storage/knowledge/browse?path=nested_wiki")
    assert resp.status_code == 200
    data = resp.json()
    # Knowledge browse usually returns list of FileItem or similar
    if isinstance(data, dict) and "items" in data:
         items = data["items"]
         assert any(i["name"] == "python.md" for i in items)
    elif isinstance(data, list):
         # Standard File Browser returns list of dicts
         assert any(i["name"] == "python.md" for i in data)
