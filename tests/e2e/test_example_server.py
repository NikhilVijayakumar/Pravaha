# Seed Test Data using tmp_path and internal API config
from pathlib import Path
import json

@pytest.fixture(scope="module")
def storage_setup(tmp_path_factory):
    """
    Setup temporary storage directory and configure the server to use it.
    Using module scope requires tmp_path_factory.
    """
    # Create temp dir
    temp_root = tmp_path_factory.mktemp("test_storage")
    output_path = temp_root / "output"
    inter_path = temp_root / "intermediate"
    know_path = temp_root / "knowledge"
    
    output_path.mkdir()
    inter_path.mkdir()
    know_path.mkdir()
    
    # Configure Server via API
    # We need to do this BEFORE running storage tests.
    config_payload = {
        "output_path": str(output_path),
        "intermediate_path": str(inter_path),
        "knowledge_path": str(know_path)
    }
    resp = client.post("/api/storage/config", json=config_payload)
    assert resp.status_code == 200, f"Config failed: {resp.text}"

    # Seed Data
    # Output - valid hierarchy for Browse [Product/Feature/File]
    (output_path / "TestProduct" / "TestFeature").mkdir(parents=True, exist_ok=True)
    with open(output_path / "TestProduct" / "TestFeature" / "result.json", "w") as f:
        json.dump({"status": "nested"}, f)
    
    # Root file (may not show in browse if strict hierarchy but readable)
    with open(output_path / "root_result.json", "w") as f:
        json.dump({"status": "root"}, f)

    # Intermediate
    with open(inter_path / "step1.json", "w") as f:
        json.dump({"step": 1}, f)
        
    (inter_path / "nested_inter").mkdir(parents=True, exist_ok=True)
    with open(inter_path / "nested_inter" / "temp.json", "w") as f:
        json.dump({"step": 2}, f)

    # Knowledge
    with open(know_path / "root_info.md", "w") as f:
        f.write("# Root Info\nContent")
    
    (know_path / "nested_wiki").mkdir(parents=True, exist_ok=True)
    with open(know_path / "nested_wiki" / "python.md", "w") as f:
        f.write("# Python\nContent")
        
    return temp_root

def test_run_calculator_utility(storage_setup):
    # Test valid addition
    payload = {
        "task_name": UtilsType.CALCULATOR.value,
        "inputs": [{"operation": "add", "a": 5, "b": 3}]
    }
    response = client.post("/api/run/utility", json=payload)
    assert response.status_code == 200
    assert response.json() == {"status": "success", "result": 8}
    
    # Test valid multiplication
    payload["inputs"] = [{"operation": "multiply", "a": 5, "b": 3}]
    response = client.post("/api/run/utility", json=payload)
    assert response.status_code == 200
    assert response.json()["result"] == 15

